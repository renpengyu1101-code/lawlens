def write(directory: Path, docs: dict) -> None:
    directory.mkdir(parents=True, exist_ok=True)
    for name, paragraphs in docs.items():
        doc = docx.Document()
        for text, kind in paragraphs:
            if kind == "标题":
                p = doc.add_paragraph()
                run = p.add_run(text)
                run.bold = True
                run.font.size = docx.shared.Pt(16)
            elif kind == "说明":
                p = doc.add_paragraph()
                run = p.add_run(text)
                run.italic = True
                run.font.size = docx.shared.Pt(9)
            else:
                doc.add_paragraph(text)
        doc.save(str(directory / name))
        print("written", name)


